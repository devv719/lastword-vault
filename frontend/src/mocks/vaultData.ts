export const getInitialSummary = (settings: CheckInSettings): VaultSummary => {
  const intervalSeconds = settings.demoMode
    ? settings.demoIntervalSeconds
    : settings.customDays * 86400;

  const remaining = settings.demoMode ? 85 : Math.floor(intervalSeconds * 0.65);
  const nextDeadline = new Date(Date.now() + remaining * 1000).toISOString();
  const lastCheckin = new Date(Date.now() - (intervalSeconds - remaining) * 1000).toISOString();

  return {
    status: 'active',
    nextDeadline,
    secondsRemaining: remaining,
    totalSecondsInInterval: intervalSeconds,
    lastCheckinAt: lastCheckin,
    totalItems: 7,
    authorizedItems: 6,
    filesCount: 3,
    notesCount: 4,
    contactsCount: 4,
    verifiedContactsCount: 3,
    assignedPercentage: 86,
  };
};
